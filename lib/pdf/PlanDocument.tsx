import { Document, Page, Text, View, StyleSheet } from "@react-pdf/renderer";
import type { PlanResult } from "@/lib/types";
import { EVENT_TYPE_LABELS } from "@/lib/types";

const formatInr = (n: number) =>
  new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 0 }).format(n);

const formatDate = (iso: string) =>
  new Date(iso).toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });

const styles = StyleSheet.create({
  page: { padding: 32, fontSize: 10, color: "#1e293b", fontFamily: "Helvetica" },
  h1: { fontSize: 20, fontWeight: 700, marginBottom: 4 },
  subtitle: { fontSize: 10, color: "#64748b", marginBottom: 16 },
  h2: { fontSize: 13, fontWeight: 700, marginTop: 18, marginBottom: 8, color: "#4338ca" },
  narrative: { fontSize: 10, lineHeight: 1.5, marginBottom: 4, padding: 10, backgroundColor: "#eef2ff", borderRadius: 4 },
  row: { flexDirection: "row", justifyContent: "space-between", paddingVertical: 4, borderBottomWidth: 0.5, borderBottomColor: "#e2e8f0" },
  rowLabel: { flex: 3 },
  rowNote: { fontSize: 8, color: "#94a3b8", marginTop: 1 },
  rowValue: { flex: 1, textAlign: "right" },
  badge: { fontSize: 8, color: "#64748b" },
  taskRow: { flexDirection: "row", paddingVertical: 4, borderBottomWidth: 0.5, borderBottomColor: "#e2e8f0" },
  warning: { fontSize: 9, padding: 8, backgroundColor: "#fef3c7", color: "#92400e", borderRadius: 4, marginBottom: 8 },
  footer: { position: "absolute", bottom: 24, left: 32, right: 32, fontSize: 8, color: "#94a3b8", textAlign: "center" },
});

export function PlanDocument({ plan }: { plan: PlanResult }) {
  const { input, budget, timeline, vendors, ideas } = plan;
  const sortedTasks = [...timeline.tasks].sort((a, b) => b.daysBeforeEvent - a.daysBeforeEvent);

  return (
    <Document title={`${input.eventName} — EventGenie Plan`}>
      <Page size="A4" style={styles.page}>
        <Text style={styles.h1}>{input.eventName}</Text>
        <Text style={styles.subtitle}>
          {EVENT_TYPE_LABELS[input.eventType]} · {input.location} · {input.guestCount} guests ·{" "}
          {formatDate(input.eventDate)}
        </Text>

        {plan.aiNarrative && <Text style={styles.narrative}>{plan.aiNarrative}</Text>}

        <Text style={styles.h2}>Budget breakdown — {formatInr(budget.total)} (~{formatInr(budget.perGuest)}/guest)</Text>
        {budget.warning && <Text style={styles.warning}>⚠ {budget.warning}</Text>}
        {budget.lines.map((line) => (
          <View key={line.category} style={styles.row}>
            <View style={styles.rowLabel}>
              <Text>{line.category}</Text>
              <Text style={styles.rowNote}>{line.note}</Text>
            </View>
            <Text style={styles.rowValue}>
              {line.percent}% · {formatInr(line.amount)}
            </Text>
          </View>
        ))}

        <Text style={styles.h2}>
          Countdown checklist ({timeline.daysUntilEvent} days to go{timeline.urgentMode ? " — urgent mode" : ""})
        </Text>
        {sortedTasks.map((task) => (
          <View key={task.id} style={styles.taskRow}>
            <Text style={{ flex: 3 }}>{task.task}</Text>
            <Text style={{ flex: 1, fontSize: 8 }}>{task.category}</Text>
            <Text style={{ flex: 1, fontSize: 8 }}>due {formatDate(task.dueDate)}</Text>
            <Text style={{ flex: 1, fontSize: 8, textAlign: "right" }}>
              {task.priority}
              {task.overdue ? " · overdue" : ""}
            </Text>
          </View>
        ))}

        <Text style={styles.h2}>Vendor checklist</Text>
        {vendors.items.map((item) => (
          <View key={item.category} style={styles.taskRow}>
            <Text style={{ flex: 2 }}>{item.category}</Text>
            <Text style={{ flex: 1, fontSize: 8 }}>{item.priority}</Text>
            <Text style={{ flex: 1, fontSize: 8 }}>{item.leadTimeWeeks}w lead time</Text>
            <Text style={{ flex: 2, fontSize: 8, textAlign: "right" }}>
              {item.bookImmediately ? "Book now — " : ""}
              {item.tips}
            </Text>
          </View>
        ))}

        <Text style={styles.h2}>Ideas</Text>
        <Text style={{ marginBottom: 4 }}>Palette: {ideas.palette.join(", ")}</Text>
        <Text style={{ marginBottom: 4 }}>Theme touches: {ideas.themeIdeas.join(" · ")}</Text>
        <Text>Activity ideas: {ideas.activityIdeas.join(" · ")}</Text>

        <Text style={styles.footer}>Generated by EventGenie · {formatDate(plan.generatedAt)}</Text>
      </Page>
    </Document>
  );
}
